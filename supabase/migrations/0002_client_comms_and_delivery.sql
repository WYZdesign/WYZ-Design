-- Spec 22 (board task 22): delivery -> proof -> referral -> repeat work.
-- Phase 1 only: schema + delivery events. No customer-facing send path is
-- enabled by this migration. Sends stay gated by per-stage allowlist flags
-- (default OFF) in src/lib/delivery.ts and are dry-run only until the copy is
-- approved and a stage is explicitly switched on.
--
-- Idempotent: safe to re-run.

-- 1. Consent: single source of truth per client.
create table if not exists public.client_comm_preferences (
  id bigint generated by default as identity primary key,
  email text not null unique,
  email_opt_in boolean not null default true,
  opt_out_at timestamptz,
  source text,
  updated_at timestamptz not null default now()
);
alter table public.client_comm_preferences enable row level security;
create index if not exists client_comm_preferences_email_idx
  on public.client_comm_preferences (lower(email));

-- 2. Delivery events: one row each time work is delivered to a client.
--    This is what the four outreach stages key off of.
create table if not exists public.delivery_events (
  id bigint generated by default as identity primary key,
  email text not null,
  client_name text,
  service_name text,
  order_id text,
  delivered_at timestamptz not null default now(),
  stage1_sent_at timestamptz,
  stage2_sent_at timestamptz,
  stage3_sent_at timestamptz,
  stage4_sent_at timestamptz,
  notes text
);
alter table public.delivery_events enable row level security;
create index if not exists delivery_events_email_idx
  on public.delivery_events (lower(email));
create index if not exists delivery_events_delivered_idx
  on public.delivery_events (delivered_at);

-- 3. Service-role-only access (matches the gift-card/order posture in 0001).
do $$
begin
  if exists (select 1 from pg_roles where rolname = 'service_role') then
    grant select, insert, update on public.client_comm_preferences to service_role;
    grant select, insert, update on public.delivery_events to service_role;
  end if;
end $$;
